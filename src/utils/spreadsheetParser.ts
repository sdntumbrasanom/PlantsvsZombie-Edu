const STORAGE_KEY = 'pvz_spreadsheet_questions';

/**
 * Loads stored questions from localStorage or initializes with default biology questions.
 */
export function getSavedQuestions(): Question[] {
  if (typeof window === 'undefined') return PRESET_BIOLOGI;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Failed to load saved questions:', err);
  }
  return PRESET_BIOLOGI;
}

/**
 * Saves questions to localStorage.
 */
export function saveQuestions(questions: Question[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(questions));
  } catch (err) {
    console.error('Failed to save questions:', err);
  }
}

/**
 * Parse lines from CSV/TSV string.
 * Supports:
 * - Tab-separated (\t) from Google Sheets / Excel copy-paste
 * - Comma-separated (,)
 * - Semicolon-separated (;)
 */
export function parseSpreadsheetData(rawText: string, ignoreHeaderRow = true): { questions: Question[]; errors: string[] } {
  const errors: string[] = [];
  const questions: Question[] = [];

  if (!rawText || !rawText.trim()) {
    errors.push('Teks kosong. Silakan tempel atau unggah data dari spreadsheet.');
    return { questions, errors };
  }

  // Detect delimiter: check first line
  const lines = rawText.split(/\r?\n/).filter(line => line.trim().length > 0);
  if (lines.length === 0) {
    errors.push('Tidak ada baris teks yang terbaca.');
    return { questions, errors };
  }

  const firstLine = lines[0];
  let delimiter = '\t'; // Default to Tab (Google Sheets / Excel copy paste)

  if (firstLine.includes('\t')) {
    delimiter = '\t';
  } else if (firstLine.includes(';') && (firstLine.split(';').length >= 3)) {
    delimiter = ';';
  } else if (firstLine.includes(',') && (firstLine.split(',').length >= 3)) {
    delimiter = ',';
  }

  // Helper to split row respecting double quotes
  const parseRow = (line: string): string[] => {
    const result: string[] = [];
    let cur = '';
    let inQuote = false;

    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"') {
        if (inQuote && line[i + 1] === '"') {
          cur += '"';
          i++; // skip escaped quote
        } else {
          inQuote = !inQuote;
        }
      } else if (char === delimiter && !inQuote) {
        result.push(cur.trim());
        cur = '';
      } else {
        cur += char;
      }
    }
    result.push(cur.trim());
    return result;
  };

  let startIndex = 0;
  if (ignoreHeaderRow && lines.length > 1) {
    const headerCols = parseRow(lines[0]).map(c => c.toLowerCase());
    const isLikelyHeader = headerCols.some(col => 
      col.includes('pertanyaan') || 
      col.includes('soal') || 
      col.includes('question') || 
      col.includes('kolom a') ||
      col.includes('jawaban') ||
      col.includes('benar') ||
      col.includes('pengecoh')
    );
    if (isLikelyHeader) {
      startIndex = 1;
    }
  }

  for (let i = startIndex; i < lines.length; i++) {
    const row = parseRow(lines[i]);
    // Kolom A = Pertanyaan, Kolom B = Jawaban Benar, Kolom C, D, E = Pengecoh
    const question = row[0] || '';
    const correctAnswer = row[1] || '';
    const distractor1 = row[2] || '';
    const distractor2 = row[3] || '';
    const distractor3 = row[4] || '';

    if (!question || !correctAnswer) {
      // Skip empty or invalid rows
      if (question || correctAnswer) {
        errors.push(`Baris ${i + 1}: Diabaikan karena pertanyaan atau jawaban benar tidak lengkap.`);
      }
      continue;
    }

    if (!distractor1) {
      errors.push(`Baris ${i + 1}: Pertanyaan "${question.slice(0, 25)}..." minimal membutuhkan 1 jawaban pengecoh di Kolom C.`);
      continue;
    }

    questions.push({
      id: `q-${Date.now()}-${i}-${Math.random().toString(36).substring(2, 6)}`,
      question,
      correctAnswer,
      distractor1,
      distractor2: distractor2 || `${correctAnswer} (Alternatif salah)`,
      distractor3: distractor3 || 'Bukan salah satu di atas',
      category: 'Spreadsheet Pengguna'
    });
  }

  if (questions.length === 0 && errors.length === 0) {
    errors.push('Format data tidak dikenali. Pastikan kolom dipisahkan oleh Tab atau Koma (Kolom A: Pertanyaan, Kolom B: Jawaban Benar, Kolom C-E: Pengecoh).');
  }

  return { questions, errors };
}

