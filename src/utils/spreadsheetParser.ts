/**
 * Export questions to downloadable TSV/CSV format
 */
export function exportQuestionsToCsv(questions: Question[]): string {
  const header = 'Pertanyaan\tJawaban Benar\tPengecoh 1\tPengecoh 2\tPengecoh 3\tKategori';
  const rows = questions.map(q => 
    `"${q.question.replace(/"/g, '""')}"\t"${q.correctAnswer.replace(/"/g, '""')}"\t"${q.distractor1.replace(/"/g, '""')}"\t"${q.distractor2.replace(/"/g, '""')}"\t"${q.distractor3.replace(/"/g, '""')}"\t"${(q.category || '').replace(/"/g, '""')}"`
  );
  return [header, ...rows].join('\n');
}
